-- Fractional Commodity Trading Ledger: core schema.
-- Portable SQL (runs on PostgreSQL and on H2 in PostgreSQL mode for tests).
-- Money:    NUMERIC(19,2)  (rupees and paise)
-- Quantity: NUMERIC(20,6)  (grams, down to a microgram)

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)             NOT NULL,
    email       VARCHAR(255)             NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE wallets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT                   NOT NULL,
    balance     NUMERIC(19, 2)           NOT NULL DEFAULT 0,
    currency    VARCHAR(3)               NOT NULL DEFAULT 'INR',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_wallets_user UNIQUE (user_id),
    CONSTRAINT fk_wallets_user FOREIGN KEY (user_id) REFERENCES users (id),
    -- Last line of defence: the database itself refuses a negative balance.
    CONSTRAINT ck_wallets_balance_non_negative CHECK (balance >= 0)
);

CREATE TABLE commodities (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol          VARCHAR(16)              NOT NULL,
    name            VARCHAR(100)             NOT NULL,
    unit            VARCHAR(16)              NOT NULL,
    price_per_unit  NUMERIC(19, 2)           NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_commodities_symbol UNIQUE (symbol),
    CONSTRAINT ck_commodities_price_positive CHECK (price_per_unit > 0)
);

CREATE TABLE holdings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT                   NOT NULL,
    commodity_id  BIGINT                   NOT NULL,
    quantity      NUMERIC(20, 6)           NOT NULL DEFAULT 0,
    cost_basis    NUMERIC(19, 2)           NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_holdings_user_commodity UNIQUE (user_id, commodity_id),
    CONSTRAINT fk_holdings_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_holdings_commodity FOREIGN KEY (commodity_id) REFERENCES commodities (id),
    CONSTRAINT ck_holdings_quantity_non_negative CHECK (quantity >= 0),
    CONSTRAINT ck_holdings_cost_non_negative CHECK (cost_basis >= 0)
);

CREATE TABLE trades (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT                   NOT NULL,
    commodity_id         BIGINT                   NOT NULL,
    side                 VARCHAR(4)               NOT NULL,
    quantity             NUMERIC(20, 6)           NOT NULL,
    price_per_unit       NUMERIC(19, 2)           NOT NULL,
    gross_amount         NUMERIC(19, 2)           NOT NULL,
    cost_basis_released  NUMERIC(19, 2),
    realized_pnl         NUMERIC(19, 2),
    client_order_id      VARCHAR(64),
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_trades_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_trades_commodity FOREIGN KEY (commodity_id) REFERENCES commodities (id),
    CONSTRAINT ck_trades_side CHECK (side IN ('BUY', 'SELL')),
    CONSTRAINT ck_trades_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_trades_amount_positive CHECK (gross_amount > 0),
    -- Idempotency: a client order id can be used only once per user.
    CONSTRAINT uk_trades_user_client_order UNIQUE (user_id, client_order_id)
);

CREATE INDEX idx_trades_user ON trades (user_id);

-- A ledger transaction (journal) groups the entries of one business event: a deposit,
-- a withdrawal, a buy or a sell. Its entries must always balance.
CREATE TABLE ledger_transactions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(16)              NOT NULL,
    user_id      BIGINT                   NOT NULL,
    trade_id     BIGINT,
    description  VARCHAR(255)             NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ledger_tx_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_ledger_tx_trade FOREIGN KEY (trade_id) REFERENCES trades (id),
    CONSTRAINT ck_ledger_tx_type CHECK (type IN ('DEPOSIT', 'WITHDRAWAL', 'BUY', 'SELL'))
);

CREATE INDEX idx_ledger_tx_user ON ledger_transactions (user_id);
CREATE INDEX idx_ledger_tx_trade ON ledger_transactions (trade_id);

CREATE TABLE ledger_entries (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ledger_transaction_id  BIGINT                   NOT NULL,
    account_type           VARCHAR(32)              NOT NULL,
    user_id                BIGINT,
    commodity_symbol       VARCHAR(16),
    direction              VARCHAR(6)               NOT NULL,
    amount                 NUMERIC(19, 2)           NOT NULL,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ledger_entries_tx FOREIGN KEY (ledger_transaction_id) REFERENCES ledger_transactions (id),
    CONSTRAINT ck_ledger_entries_direction CHECK (direction IN ('DEBIT', 'CREDIT')),
    CONSTRAINT ck_ledger_entries_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_ledger_entries_account CHECK (
        account_type IN ('USER_CASH', 'USER_COMMODITY', 'EXTERNAL_FUNDING', 'REALIZED_PNL'))
);

CREATE INDEX idx_ledger_entries_tx ON ledger_entries (ledger_transaction_id);
CREATE INDEX idx_ledger_entries_account ON ledger_entries (account_type, user_id, commodity_symbol);
